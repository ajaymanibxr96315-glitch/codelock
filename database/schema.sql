-- CodeLock student progress schema (Oracle Database 12c or newer)
--
-- Run once in the schema CodeLock will connect as:
--   sqlplus codelock/your_password@//host:1521/service @database/schema.sql
--
-- Then set CODELOCK_ORACLE_USER, CODELOCK_ORACLE_PASSWORD and CODELOCK_ORACLE_DSN
-- before starting the app. Without those variables CodeLock uses its local
-- SQLite store instead. Passwords are hashed by the Python app (PBKDF2-SHA256);
-- only the hash and salt are stored here.

SET DEFINE OFF;

