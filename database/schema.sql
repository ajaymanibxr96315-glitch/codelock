CREATE TABLE students (
    id            NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    username      VARCHAR2(64)  NOT NULL,
    display_name  VARCHAR2(80)  NOT NULL,
    password_hash VARCHAR2(128) NOT NULL,
    salt          VARCHAR2(64)  NOT NULL,
    created_at    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    last_login    TIMESTAMP,
    CONSTRAINT uq_students_username UNIQUE (username)
);

CREATE TABLE progress (
    student_id    NUMBER        NOT NULL,
    track_key     VARCHAR2(32)  NOT NULL,
    current_index NUMBER(3)     DEFAULT 0 NOT NULL,
    completed     NUMBER(6)     DEFAULT 0 NOT NULL,
    attempts      NUMBER(6)     DEFAULT 0 NOT NULL,
    total_seconds NUMBER(12, 3) DEFAULT 0 NOT NULL,
    best_seconds  NUMBER(12, 3),
    updated_at    TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_progress PRIMARY KEY (student_id, track_key),
    CONSTRAINT fk_progress_student FOREIGN KEY (student_id)
        REFERENCES students (id) ON DELETE CASCADE
);

CREATE TABLE attempts (
    id               NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    student_id       NUMBER        NOT NULL,
    track_key        VARCHAR2(32)  NOT NULL,
    problem_key      VARCHAR2(64)  NOT NULL,
    duration_seconds NUMBER(12, 3) NOT NULL,
    passed           NUMBER(1)     NOT NULL,
    tests_passed     NUMBER(6)     DEFAULT 0 NOT NULL,
    tests_total      NUMBER(6)     DEFAULT 0 NOT NULL,
    created_at       TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT fk_attempts_student FOREIGN KEY (student_id)
        REFERENCES students (id) ON DELETE CASCADE,
    CONSTRAINT ck_attempts_passed CHECK (passed IN (0, 1))
);

CREATE INDEX idx_attempts_student ON attempts (student_id, created_at);

-- Academic workspace data is owned by the authenticated student. Topic trees
-- and generated content are JSON CLOBs so SQLite and Oracle share one shape.
CREATE TABLE exam_workspaces (
    workspace_id      NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    student_id        NUMBER NOT NULL,
    subject           VARCHAR2(160) NOT NULL,
    course_level      VARCHAR2(120),
    exam_date         VARCHAR2(10),
    total_marks       NUMBER(8) DEFAULT 100 NOT NULL,
    duration_minutes  NUMBER(6) DEFAULT 180 NOT NULL,
    syllabus_filename VARCHAR2(512),
    source_text       CLOB,
    topics_json       CLOB,
    syllabus_approved NUMBER(1) DEFAULT 0 NOT NULL,
    notes_json        CLOB,
    questions_json    CLOB,
    question_bank_fingerprint VARCHAR2(64) DEFAULT '' NOT NULL,
    created_at        TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at        TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT fk_exam_workspace_student FOREIGN KEY (student_id)
        REFERENCES students (id) ON DELETE CASCADE,
    CONSTRAINT ck_exam_workspace_approved CHECK (syllabus_approved IN (0, 1))
);

CREATE INDEX idx_exam_workspaces_student
    ON exam_workspaces (student_id, updated_at);

-- Normalized question bank. Generated JSON is the source document; this table
-- gives practice/mock sessions stable question identities and topic metadata.
CREATE TABLE exam_questions (
    question_id     NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    workspace_id    NUMBER NOT NULL,
    student_id      NUMBER NOT NULL,
    unit_title      VARCHAR2(160),
    topic           VARCHAR2(240) NOT NULL,
    question_type   VARCHAR2(64) NOT NULL,
    difficulty      VARCHAR2(16) NOT NULL,
    bloom_level     VARCHAR2(16) NOT NULL,
    marks           NUMBER(3) NOT NULL,
    prompt          VARCHAR2(1000) NOT NULL,
    options_json    CLOB,
    answer          VARCHAR2(4000) NOT NULL,
    explanation     CLOB,
    source_quote    CLOB,
    source_kind     VARCHAR2(16) DEFAULT 'ai' NOT NULL,
    source_ref      VARCHAR2(512),
    is_active       NUMBER(1) DEFAULT 1 NOT NULL,
    created_at      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT fk_exam_question_workspace FOREIGN KEY (workspace_id)
        REFERENCES exam_workspaces (workspace_id) ON DELETE CASCADE,
    CONSTRAINT fk_exam_question_student FOREIGN KEY (student_id)
        REFERENCES students (id) ON DELETE CASCADE,
    CONSTRAINT ck_exam_question_active CHECK (is_active IN (0, 1)),
    CONSTRAINT ck_exam_question_marks CHECK (marks BETWEEN 1 AND 100)
);

CREATE INDEX idx_exam_questions_workspace
    ON exam_questions (workspace_id, is_active, topic);

CREATE TABLE exam_sessions (
    session_id      NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    student_id      NUMBER NOT NULL,
    workspace_id    NUMBER NOT NULL,
    mode            VARCHAR2(16) NOT NULL,
    status          VARCHAR2(16) DEFAULT 'in_progress' NOT NULL,
    blueprint_json  CLOB,
    total_marks     NUMBER(8) DEFAULT 0 NOT NULL,
    score_marks     NUMBER(12, 3) DEFAULT 0 NOT NULL,
    needs_review    NUMBER(6) DEFAULT 0 NOT NULL,
    duration_limit_seconds NUMBER(10) DEFAULT 0 NOT NULL,
    elapsed_seconds NUMBER(12, 3) DEFAULT 0 NOT NULL,
    started_at      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    submitted_at    TIMESTAMP,
    created_at      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT fk_exam_session_student FOREIGN KEY (student_id)
        REFERENCES students (id) ON DELETE CASCADE,
    CONSTRAINT fk_exam_session_workspace FOREIGN KEY (workspace_id)
        REFERENCES exam_workspaces (workspace_id) ON DELETE CASCADE,
    CONSTRAINT ck_exam_session_mode CHECK (mode IN ('practice', 'mock')),
    CONSTRAINT ck_exam_session_status
        CHECK (status IN ('in_progress', 'submitted', 'abandoned'))
);

CREATE INDEX idx_exam_sessions_student
    ON exam_sessions (student_id, workspace_id, created_at);

CREATE TABLE exam_responses (
    response_id     NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    session_id      NUMBER NOT NULL,
    student_id      NUMBER NOT NULL,
    workspace_id    NUMBER NOT NULL,
    question_id     NUMBER NOT NULL,
    position        NUMBER(6) NOT NULL,
    unit_title      VARCHAR2(160),
    topic           VARCHAR2(240) NOT NULL,
    question_type   VARCHAR2(64) NOT NULL,
    marks           NUMBER(3) NOT NULL,
    student_answer  CLOB,
    is_correct      NUMBER(1),
    awarded_marks   NUMBER(8, 3) DEFAULT 0 NOT NULL,
    review_status   VARCHAR2(32) DEFAULT 'unanswered' NOT NULL,
    question_snapshot_json CLOB,
    answered_at     TIMESTAMP,
    CONSTRAINT uq_exam_response_question UNIQUE (session_id, question_id),
    CONSTRAINT fk_exam_response_session FOREIGN KEY (session_id)
        REFERENCES exam_sessions (session_id) ON DELETE CASCADE,
    CONSTRAINT fk_exam_response_student FOREIGN KEY (student_id)
        REFERENCES students (id) ON DELETE CASCADE,
    CONSTRAINT fk_exam_response_workspace FOREIGN KEY (workspace_id)
        REFERENCES exam_workspaces (workspace_id) ON DELETE CASCADE,
    CONSTRAINT ck_exam_response_correct CHECK (is_correct IN (0, 1) OR is_correct IS NULL)
);

CREATE INDEX idx_exam_responses_session
    ON exam_responses (session_id, position);

CREATE INDEX idx_exam_responses_topic
    ON exam_responses (student_id, workspace_id, topic);

CREATE OR REPLACE PACKAGE codelock_api AS
    FUNCTION register_student(
        p_username      IN VARCHAR2,
        p_display_name  IN VARCHAR2,
        p_password_hash IN VARCHAR2,
        p_salt          IN VARCHAR2
    ) RETURN NUMBER;

    PROCEDURE get_credentials(
        p_username      IN  VARCHAR2,
        o_student_id    OUT NUMBER,
        o_display_name  OUT VARCHAR2,
        o_password_hash OUT VARCHAR2,
        o_salt          OUT VARCHAR2
    );

    PROCEDURE touch_login(p_student_id IN NUMBER);

    PROCEDURE record_attempt(
        p_student_id       IN NUMBER,
        p_track_key        IN VARCHAR2,
        p_problem_key      IN VARCHAR2,
        p_duration_seconds IN NUMBER,
        p_passed           IN NUMBER,
        p_tests_passed     IN NUMBER,
        p_tests_total      IN NUMBER,
        p_next_index       IN NUMBER
    );

    PROCEDURE get_progress(
        p_student_id    IN  NUMBER,
        p_track_key     IN  VARCHAR2,
        o_current_index OUT NUMBER,
        o_completed     OUT NUMBER,
        o_attempts      OUT NUMBER,
        o_total_seconds OUT NUMBER,
        o_best_seconds  OUT NUMBER
    );
END codelock_api;
/

CREATE OR REPLACE PACKAGE BODY codelock_api AS

    FUNCTION register_student(
        p_username      IN VARCHAR2,
        p_display_name  IN VARCHAR2,
        p_password_hash IN VARCHAR2,
        p_salt          IN VARCHAR2
    ) RETURN NUMBER IS
        v_student_id NUMBER;
    BEGIN
        INSERT INTO students (username, display_name, password_hash, salt)
        VALUES (LOWER(TRIM(p_username)), p_display_name, p_password_hash, p_salt)
        RETURNING id INTO v_student_id;
        RETURN v_student_id;
    END register_student;

    PROCEDURE get_credentials(
        p_username      IN  VARCHAR2,
        o_student_id    OUT NUMBER,
        o_display_name  OUT VARCHAR2,
        o_password_hash OUT VARCHAR2,
        o_salt          OUT VARCHAR2
    ) IS
    BEGIN
        SELECT id, display_name, password_hash, salt
          INTO o_student_id, o_display_name, o_password_hash, o_salt
          FROM students
         WHERE username = LOWER(TRIM(p_username));
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            o_student_id := NULL;
    END get_credentials;

    PROCEDURE touch_login(p_student_id IN NUMBER) IS
    BEGIN
        UPDATE students
           SET last_login = SYSTIMESTAMP
         WHERE id = p_student_id;
    END touch_login;

    PROCEDURE record_attempt(
        p_student_id       IN NUMBER,
        p_track_key        IN VARCHAR2,
        p_problem_key      IN VARCHAR2,
        p_duration_seconds IN NUMBER,
        p_passed           IN NUMBER,
        p_tests_passed     IN NUMBER,
        p_tests_total      IN NUMBER,
        p_next_index       IN NUMBER
    ) IS
    BEGIN
        INSERT INTO attempts (
            student_id, track_key, problem_key, duration_seconds,
            passed, tests_passed, tests_total
        ) VALUES (
            p_student_id, p_track_key, p_problem_key, p_duration_seconds,
            p_passed, p_tests_passed, p_tests_total
        );

        MERGE INTO progress t
        USING (
            SELECT p_student_id AS student_id, p_track_key AS track_key
              FROM dual
        ) source
        ON (t.student_id = source.student_id
            AND t.track_key = source.track_key)
        WHEN MATCHED THEN
            UPDATE SET
                current_index = CASE
                    WHEN p_passed = 1 THEN p_next_index
                    ELSE current_index
                END,
                completed = completed + p_passed,
                attempts = attempts + 1,
                total_seconds = total_seconds + p_duration_seconds,
                best_seconds = CASE
                    WHEN p_passed = 1 THEN LEAST(
                        NVL(best_seconds, p_duration_seconds),
                        p_duration_seconds
                    )
                    ELSE best_seconds
                END,
                updated_at = SYSTIMESTAMP
        WHEN NOT MATCHED THEN
            INSERT (
                student_id, track_key, current_index, completed,
                attempts, total_seconds, best_seconds, updated_at
            ) VALUES (
                p_student_id, p_track_key,
                CASE WHEN p_passed = 1 THEN p_next_index ELSE 0 END,
                p_passed, 1, p_duration_seconds,
                CASE WHEN p_passed = 1 THEN p_duration_seconds ELSE NULL END,
                SYSTIMESTAMP
            );
    END record_attempt;

    PROCEDURE get_progress(
        p_student_id    IN  NUMBER,
        p_track_key     IN  VARCHAR2,
        o_current_index OUT NUMBER,
        o_completed     OUT NUMBER,
        o_attempts      OUT NUMBER,
        o_total_seconds OUT NUMBER,
        o_best_seconds  OUT NUMBER
    ) IS
    BEGIN
        SELECT current_index, completed, attempts, total_seconds, best_seconds
          INTO o_current_index, o_completed, o_attempts, o_total_seconds, o_best_seconds
          FROM progress
         WHERE student_id = p_student_id
           AND track_key = p_track_key;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            o_current_index := 0;
            o_completed := 0;
            o_attempts := 0;
            o_total_seconds := 0;
            o_best_seconds := NULL;
    END get_progress;

END codelock_api;
/

CREATE OR REPLACE VIEW student_overview AS
SELECT s.id,
       s.username,
       s.display_name,
       p.track_key,
       p.current_index,
       p.completed,
       p.attempts,
       ROUND(p.total_seconds, 1) AS total_seconds,
       ROUND(p.best_seconds, 1) AS best_seconds,
       p.updated_at
  FROM students s
  LEFT JOIN progress p ON p.student_id = s.id;

COMMIT;
